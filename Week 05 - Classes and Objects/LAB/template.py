class Record:
    def __init__(self, label, value, limit):
        self.label = label
        self.value = value
        self.limit = limit
    
    def percent(self):
        return (self.value / self.limit) * 100
        
    def status(self):
        percentage = self.percent()
        if percentage >= 100:
            return "OVER LIMIT"
        elif percentage >= 90:
            return "WARNING"
        return "OK"
        


